"""Fail if any file in this repository is a copy of a file from the legacy codebase (NFR-09.6, D13).

The rewrite is a clean reimplementation: no legacy source, data file, image or document may be
copied in. `legacy-sha256.txt` holds a SHA-256 of every legacy file (no legacy content).

Each file is compared twice: as stored, and normalised (UTF-8/UTF-16 byte order mark removed,
CRLF turned into LF), so a copy with changed line endings is still caught.

Usage (from the repository root):
  python -I tools/legacy-check/check_legacy_files.py
      Check every file tracked by git. Exit code 1 on a match.
  python -I tools/legacy-check/check_legacy_files.py --generate <legacy dir>
      Rewrite legacy-sha256.txt from a checkout of the legacy codebase.
"""
import hashlib
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LIST = HERE / "legacy-sha256.txt"
# Smaller files (empty markers, one-line configs) are too generic to say anything.
MIN_SIZE = 64
BOMS = (b"\xef\xbb\xbf", b"\xff\xfe", b"\xfe\xff")


def digests(data: bytes) -> set[str]:
    raw = hashlib.sha256(data).hexdigest()
    norm = data
    for bom in BOMS:
        if norm.startswith(bom):
            norm = norm[len(bom):]
            break
    norm = norm.replace(b"\r\n", b"\n").replace(b"\r\x00\n\x00", b"\n\x00")
    return {raw, hashlib.sha256(norm).hexdigest()}


def generate(legacy_dir: Path) -> int:
    lines = []
    for path in sorted(p for p in legacy_dir.rglob("*") if p.is_file()):
        if ".git" in path.parts or path.stat().st_size < MIN_SIZE:
            continue
        rel = path.relative_to(legacy_dir).as_posix()
        for digest in sorted(digests(path.read_bytes())):
            lines.append(f"{digest}  {rel}")
    header = (
        "# SHA-256 of every legacy Translation Aggregator file of at least "
        f"{MIN_SIZE} bytes (raw and normalised).\n"
        "# Generated by check_legacy_files.py --generate. Contains no legacy content.\n"
    )
    LIST.write_text(header + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(lines)} hashes to {LIST}")
    return 0


def check() -> int:
    known: dict[str, str] = {}
    for line in LIST.read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            digest, _, name = line.partition("  ")
            known[digest] = name
    tracked = subprocess.run(
        ["git", "ls-files", "-z"], check=True, capture_output=True
    ).stdout.decode("utf-8").split("\0")
    hits = []
    checked = 0
    for rel in filter(None, tracked):
        path = Path(rel)
        if not path.is_file() or path.resolve() == LIST or path.stat().st_size < MIN_SIZE:
            continue
        checked += 1
        for digest in digests(path.read_bytes()):
            if digest in known:
                hits.append((rel, known[digest]))
                break
    if hits:
        for rel, legacy in hits:
            print(f"::error file={rel}::{rel} is a copy of legacy file {legacy} (D13: no legacy files)")
        print(f"{len(hits)} file(s) match legacy files.")
        return 1
    print(f"OK: {checked} files checked against {len(known)} legacy hashes, no match.")
    return 0


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--generate":
        sys.exit(generate(Path(sys.argv[2])))
    if len(sys.argv) == 1:
        sys.exit(check())
    print(__doc__)
    sys.exit(2)
